from hkexdb import extractor, selectors      # noqa: E402


def _primary(ex):
    comps = [{"anchor": c.anchor, "window": c.window, "label": c.label,
              "stated_pct": c.stated_pct, "stated_direction": c.stated_direction,
              "page": c.page, "quote": c.quote} for c in ex.comparisons]
    pick = selectors.select_primary_premium(comps)
    return str(pick.signed_pct) if pick else None


def test_the_section_header_can_also_be_called_要約價比較():
    """01633 上諭集團的小标题是「要約價比較」，不是「價值比較」。

    差两个字，整节就切不出来。这单靠全文兜底捞回来了，
    但兜底比按节切粗糙 —— 小标题认得越全越好。
    """
    ex = extractor.extract("聯合公告 強制性無條件現金要約", P01633)
    assert len(ex.comparisons) == 5
    assert _primary(ex) == "-35.66"


def test_lettered_items_are_recognised_as_item_markers():
    """01875 東曜藥業的价值比较用 (a)(b)(c) 编号，不是 (i)(ii) 也不是 1. 2.

    只认两种编号时，这一节 12 条比较**只切出 1 条**，主值溢价率取到
    99.00%（未受干扰日收市价）而不是 114.67%（未受干扰日前30日均价）——
    差 15 个百分点，而且表里看起来完全正常。
    """
    ex = extractor.extract("聯合公告 自願有條件現金要約", P01875)
    assert len(ex.comparisons) >= 7, "字母编号没被认出来，整节切不开"
    assert _primary(ex) == "114.67"


